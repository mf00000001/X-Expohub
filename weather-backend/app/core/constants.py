# ──────────────────────────────────────────────
TEMP_UNITS: dict[str, str] = {
    "celsius": "℃",
    "fahrenheit": "℉",
}


def celsius_to_fahrenheit(celsius: float) -> float:
    """摄氏度转华氏度"""
    return round(celsius * 9 / 5 + 32, 1)


def fahrenheit_to_celsius(fahrenheit: float) -> float:
    """华氏度转摄氏度"""
    return round((fahrenheit - 32) * 5 / 9, 1)


