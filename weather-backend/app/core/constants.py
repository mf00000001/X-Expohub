# ──────────────────────────────────────────────
# AQI 等级映射（中国标准）
# ──────────────────────────────────────────────
AQI_LEVEL_MAP: dict[str, tuple[int, int]] = {
    "优": (0, 50),
    "良": (51, 100),
    "轻度污染": (101, 150),
    "中度污染": (151, 200),
    "重度污染": (201, 300),
    "严重污染": (301, 500),
}

AQI_LEVEL_COLORS: dict[str, str] = {
    "优": "#00E400",
    "良": "#FFFF00",
    "轻度污染": "#FF7E00",
    "中度污染": "#FF0000",
    "重度污染": "#99004C",
    "严重污染": "#7E0023",
}


def get_aqi_level(aqi: int) -> str:
    """根据 AQI 值返回等级名称"""
    for level, (low, high) in AQI_LEVEL_MAP.items():
        if low <= aqi <= high:
            return level
    return "未知"


def get_aqi_color(aqi: int) -> str:
    """根据 AQI 值返回对应颜色"""
    return AQI_LEVEL_COLORS.get(get_aqi_level(aqi), "#808080")


