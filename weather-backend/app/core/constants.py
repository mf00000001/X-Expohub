def get_wind_level(speed_m_s: float) -> tuple[int, str]:
    """根据风速 (m/s) 返回风力等级和名称"""
    for level, (name, (low, high)) in WIND_LEVEL_MAP.items():
        if low <= speed_m_s <= high:
            return level, name
    return 12, "飓风"


